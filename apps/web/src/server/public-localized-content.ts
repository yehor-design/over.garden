/**
 * What a guide or an answer changes per language. The editorial meta a
 * translation carries is the part a reader reads — the basis and the
 * qualifications; the sources, the dates and the review state are the same
 * in every language and live with the piece itself.
 */
type KnowledgeEditorialTranslation = Pick<
  PublicKnowledgeEditorialMeta,
  "basis" | "qualifications"
>;

type GuideTranslation = Partial<
  Pick<
    GuideContent,
    "title" | "description" | "outcome" | "steps" | "evidenceTitle"
  >
> & { editorial: KnowledgeEditorialTranslation };

type AnswerTranslation = Partial<
  Pick<
    AnswerPageContent,
    | "question"
    | "title"
    | "description"
    | "conciseAnswer"
    | "causes"
    | "observations"
    | "faqs"
    | "evidenceTitle"
  >
> & {
  productHelp: Omit<AnswerProductHelp, "guideSlug">;
  editorial: KnowledgeEditorialTranslation;
};

