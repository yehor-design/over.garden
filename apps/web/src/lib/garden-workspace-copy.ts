const COPY_BY_LOCALE: Record<InterfaceLocale, GardenWorkspaceCopy> = {
  uk: UK_COPY,
  bg: BG_COPY,
  ru: RU_COPY,
};

const DATE_LOCALE_BY_INTERFACE_LOCALE: Record<InterfaceLocale, string> = {
  uk: "uk-UA",
  bg: "bg-BG",
  ru: "ru-RU",
};

export function getGardenWorkspaceCopy(
  locale: InterfaceLocale,
): GardenWorkspaceCopy {
  return COPY_BY_LOCALE[locale];
}

export function formatGardenWorkspaceTemplate(
  template: string,
  values: Record<string, string | number>,
) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export interface GardenCountForms {
  one: string;
  few: string;
  many: string;
  other: string;
}

export function formatGardenCount(
  locale: InterfaceLocale,
  count: number,
  forms: GardenCountForms,
) {
  return `${count} ${selectGardenPluralForm(locale, count, forms)}`;
}

export function selectGardenPluralForm<T>(
  locale: InterfaceLocale,
  count: number,
  forms: { one: T; few: T; many: T; other: T },
) {
  const category = new Intl.PluralRules(
    DATE_LOCALE_BY_INTERFACE_LOCALE[locale],
  ).select(count) as keyof typeof forms;
  return forms[category] ?? forms.other;
}

export function formatGardenWorkspaceDate(
  locale: InterfaceLocale,
  value: Date | string,
  style: "long" | "short" = "long",
) {
  const date = value instanceof Date ? value : new Date(value);
  return date.toLocaleDateString(
    DATE_LOCALE_BY_INTERFACE_LOCALE[locale],
    style === "short"
      ? { month: "short", day: "numeric" }
      : { year: "numeric", month: "short", day: "numeric" },
  );
}

export function localizedJournalSaveErrorMessage(
  locale: InterfaceLocale,
  error: unknown,
) {
  const copy = getGardenWorkspaceCopy(locale).composer;
  const message = error instanceof Error ? error.message : "";

  if (/photo/i.test(message)) {
    return /no longer has/i.test(message)
      ? copy.photo.noLongerAvailable
      : copy.photo.uploadError;
  }

  return copy.messages.genericSaveError;
}

export function buildGardenCatalogTrustMetadata(
  locale: InterfaceLocale,
  input: CatalogTrustInput,
): CatalogTrustMetadata {
  const base = catalogSuggestionTrustMetadata(input);
  const copy = getGardenWorkspaceCopy(locale).composer.catalogTrust;
  const state = catalogTrustState(input);
  const trustLabel =
    input.status === "blocked"
      ? copy.states.blocked
      : state === "curated"
        ? copy.states.curated
        : state === "source_backed"
          ? copy.states.sourceBacked
          : state === "candidate"
            ? copy.states.candidate
            : state === "user_added"
              ? copy.states.userAdded
              : state === "quarantined"
                ? copy.states.quarantined
                : copy.states.rejected;
  const disambiguationLabel = [
    localizedCatalogTrustKind(input.catalogKind, copy.kinds),
    base.sourceLabel,
    input.locale || null,
  ]
    .filter(Boolean)
    .join(" · ");

  return {
    ...base,
    trustLabel,
    sourceCaveat: localizedCatalogSourceCaveat(input, state, copy.caveats),
    disambiguationLabel,
  };
}

function localizedCatalogTrustKind(
  value: CatalogTrustInput["catalogKind"],
  copy: GardenWorkspaceCopy["composer"]["catalogTrust"]["kinds"],
) {
  if (value === "breed") return copy.breed;
  if (value === "species") return copy.species;
  if (value === "plant_variety") return copy.plantVariety;
  return copy.identity;
}

function localizedCatalogSourceCaveat(
  input: CatalogTrustInput,
  state: ReturnType<typeof catalogTrustState>,
  copy: GardenWorkspaceCopy["composer"]["catalogTrust"]["caveats"],
) {
  if (state === "curated") return copy.curated;
  if (state === "user_added") return copy.userAdded;
  if (state === "quarantined") return copy.quarantined;
  if (state === "rejected") {
    return input.status === "blocked" ? copy.rejectedBlocked : copy.rejected;
  }
  if (input.status === "held" || input.status === "review_needed") {
    return copy.reviewPending;
  }
  if (input.status === "promoted") return copy.promoted;

  switch (input.source) {
    case "grin_genebank_candidate":
    case "grin-global":
      return copy.grin;
    case "eu_oj_eur_lex_common_catalogue":
      return copy.euOfficialJournal;
    case "eu_common_catalogue_bg":
      return copy.euBg;
    case "ua_state_register":
      return copy.uaRegister;
    case "species_backbone":
      return copy.species;
    case "ua_official_bee_breed":
      return copy.beeBreed;
    case "vertebrate_breed_ontology":
      return copy.animalBreed;
    case "internal_seed":
      return copy.internal;
    default:
      return copy.generic;
  }
}
