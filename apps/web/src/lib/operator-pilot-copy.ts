export function operatorPilotLabel(
  locale: InterfaceLocale,
  namespace:
    | "segments"
    | "activationResults"
    | "returnReasons"
    | "objections"
    | "observedValues"
    | "nextActions"
    | "cohorts"
    | "coreBuckets"
    | "diagnosticBuckets",
  value: string,
) {
  const labels = getOperatorPilotCopy(locale)[namespace] as Record<
    string,
    string
  >;
  return labels[value] ?? value;
}

export function operatorPilotOptions<T extends string>(
  locale: InterfaceLocale,
  namespace:
    | "segments"
    | "activationResults"
    | "returnReasons"
    | "objections"
    | "observedValues"
    | "nextActions"
    | "cohorts",
  values: readonly T[],
) {
  return values.map((value) => ({
    value,
    label: operatorPilotLabel(locale, namespace, value),
  }));
}

export function operatorDecisionSignalLabel(
  locale: InterfaceLocale,
  signal: string,
) {
  const labels = getOperatorPilotCopy(locale).decision.signals as Record<
    string,
    string
  >;
  return labels[signal] ?? signal;
}
