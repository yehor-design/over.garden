const TRUST_SURFACE_COPY: Record<InterfaceLocale, TrustSurfaceCopy> = {
  uk: UK_COPY,
  bg: BG_COPY,
  ru: RU_COPY,
};

export function getTrustSurfaceCopy(locale: InterfaceLocale): TrustSurfaceCopy {
  return TRUST_SURFACE_COPY[locale];
}

export function formatTrustAuthPrompt(
  locale: InterfaceLocale,
  activationSource: ActivationSource,
  catalogName?: string | null,
) {
  const prompts = getTrustSurfaceCopy(locale).authPanel.prompts;

  if (activationSource === "public_variety" && catalogName) {
    return formatTrustTemplate(prompts.publicVariety, { catalogName });
  }
  if (activationSource === "homepage") return prompts.homepage;
  return prompts.directGarden;
}

export function formatTrustTemplate(
  template: string,
  values: Readonly<Record<string, string>>,
) {
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, value),
    template,
  );
}

export function getLocalizedAuthClientErrorMessage(
  locale: InterfaceLocale,
  error: { message?: string; status?: number } | null | undefined,
) {
  const copy = getTrustSurfaceCopy(locale).authPanel;
  const kind = classifyAuthClientError(error);

  if (kind === "invalid_credentials") return copy.invalidCredentials;
  return null;
}

export type LocalizedEmailSignUpResult =
  | { kind: "accepted"; message: string }
  | { kind: "error"; message: string };

export function getLocalizedEmailSignUpResult(
  locale: InterfaceLocale,
  error: { message?: string; status?: number } | null | undefined,
): LocalizedEmailSignUpResult {
  const copy = getTrustSurfaceCopy(locale).authPanel;
  const kind = classifyAuthClientError(error);

  // Better Auth deliberately makes a new unverified account and an existing
  // email indistinguishable. Preserve that enumeration-resistant boundary.
  if (!error || kind === "existing_account") {
    return { kind: "accepted", message: copy.signUpRequestAccepted };
  }

  return {
    kind: "error",
    message:
      getLocalizedAuthClientErrorMessage(locale, error) ??
      copy.createAccountError,
  };
}

export function getLocalizedOAuthErrorMessage(
  locale: InterfaceLocale,
  error: string | string[] | undefined,
) {
  const code = oauthErrorCodeForRedirect(error);
  if (!code) return null;
  return OAUTH_ERROR_COPY[locale][code];
}

export function getLocalizedErasureStatusCopy(
  locale: InterfaceLocale,
  status: string,
  handledStatus: string | null,
) {
  const copy = getTrustSurfaceCopy(locale).erasure;
  const statusCopy =
    copy.status[status as ErasureRequestStatusCopyKey] ?? copy.status.submitted;
  const handledCopy = handledStatus
    ? (copy.handledStatus[
        handledStatus as ErasureRequestHandledStatusCopyKey
      ] ?? null)
    : null;

  return { ...statusCopy, handled: handledCopy };
}

